function unify(text) {
  const lines = text.split('\n');
  let fence = false;
  return lines.map((line) => {
    const t = line.trimStart();
    if (t.startsWith('```') || t.startsWith('~~~')) { fence = !fence; return line; }
    if (fence) return line;                      // 代码块内不动
    return line.split(/(`[^`]*`)/).map((seg) => {
      if (seg.startsWith('`') && seg.endsWith('`')) return seg;   // 行内代码不动
      let s = seg;
      for (const [cn, jp] of Object.entries(MAP)) s = s.split(cn).join(jp);
      return s;
    }).join('');
  }).join('\n');
}
