/**
* 从 emoji_id `<uin>_0_0_0_<MD5>_0_0` 提取中段 32 位大写 hex MD5。
* 格式固定（fetch/delete/move 共用），取第 5 段。解析失败抛错——比静默
* 传空串让服务端拒绝更早定位问题。
*/
function md5FromEmojiId(emojiId) {
	const md5 = emojiId.split("_")[4];
	if (!md5 || md5.length !== 32 || !/^[0-9a-fA-F]{32}$/.test(md5)) throw new Error(`invalid emoji_id (cannot extract md5): ${emojiId}`);
	return md5.toUpperCase();
}
